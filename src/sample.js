这句简单的话让我看了很久的天空。云果然走得很快，形状一直在改变，像某种不着急定稿的文字。有的展开，有的消散，没有一朵必须保持原来的样子。
我想，回去以后，事情大概还是那些事情。桌上会有未读的消息，日历上会有需要完成的工作，厨房里可能还有没洗的杯子。树林没有替我解决它们，但它教会我，在它们之间可以有一条小路。
只要偶尔沿着那条小路走一走，就能记起，生活还有别的声音，别的速度，以及别的光。

