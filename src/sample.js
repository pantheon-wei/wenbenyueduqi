风吹过草地的时候，草没有记住每一次摇晃。它们继续生长，继续在根部积蓄力量。这不是遗忘，而是一种把注意力放回自身的能力。
远处有一群鸟飞起，在天空中划过很小的弧线。它们没有始终排成整齐的队伍，却始终保持着彼此能看见的距离。有些同行也许不需要完全一致，只需要偶尔确认，彼此仍在路上。
我闭上眼睛，听了一会儿风。没有特殊的领悟，也没有突然改变的人生。只是呼吸比之前更深，肩膀比之前更松，心里的事情不再挤作一团。
